import type { Pattern, PatternView } from "@autotelic/protocol"
import { authoredLines } from "./authored.ts"
import { plural } from "./text.ts"

/*
 * `PATTERNS.md` and `patterns.json`.
 *
 * The menu answers "what exists?"; this view answers "what is the shape, why does it hold,
 * and what is it connected to?". The Markdown is the human reading; the JSON is the same
 * view for an agent that wants to sort or filter without re-deriving stability.
 */

const list = (items: ReadonlyArray<string>, limit: number): string => {
  const shown = items
    .slice(0, limit)
    .map((item) => `\`${item}\``)
    .join(", ")
  const rest = items.length - limit
  return rest > 0 ? `${shown} +${String(rest)} more` : shown
}

const factorLine = (pattern: Pattern): string =>
  `tier ${pattern.factors.tier.toFixed(2)} · adoption ${pattern.factors.adoption.toFixed(2)} · ownership ${pattern.factors.ownership.toFixed(2)} · variant ${pattern.factors.variant.toFixed(2)} · documented ${pattern.factors.documented.toFixed(2)}`

const relationLine = (pattern: Pattern): string => {
  if (pattern.relations.length === 0) return ""
  const grouped = new Map<string, Array<string>>()
  for (const relation of pattern.relations) {
    const group = grouped.get(relation.kind) ?? []
    group.push(relation.target)
    grouped.set(relation.kind, group)
  }
  const parts = [...grouped].map(([kind, targets]) => `${kind} ${list(targets, 4)}`)
  return parts.join("; ")
}

const patternLine = (pattern: Pattern): ReadonlyArray<string> => {
  const context = [
    pattern.tier,
    `${plural(pattern.usedBy, ["importer", "importers"])}`,
    `${plural(pattern.owners.length, ["owner", "owners"])}`,
  ].join(" · ")
  const text = authoredLines(pattern)
  const lines = [
    `- \`${pattern.name}\` — \`${pattern.path}\` — stability ${pattern.stability.toFixed(2)} — ${context}${text.length === 0 ? "" : ` — ${text.join(" — ")}`}`,
    `  factors: ${factorLine(pattern)}`,
  ]
  const relations = relationLine(pattern)
  if (relations !== "") lines.push(`  relations: ${relations}`)
  if (pattern.composedOf.length > 0) {
    lines.push(`  composed of: ${list(pattern.composedOf, 6)}`)
  }
  return lines
}

const compositionSection = (pattern: Pattern): ReadonlyArray<string> => {
  const authoredText = authoredLines(pattern)
  const lines = [
    `### \`${pattern.name}\` — \`${pattern.path}\``,
    "",
    `- stability: ${pattern.stability.toFixed(2)} — ${factorLine(pattern)}`,
    `- context: ${pattern.tier}; ${plural(pattern.usedBy, ["importer", "importers"])}; ${plural(pattern.owners.length, ["owner", "owners"])}`,
  ]
  if (authoredText.length > 0) lines.push(`- authored: ${authoredText.join(" — ")}`)
  if (pattern.blocks !== undefined && pattern.blocks.length > 0) {
    lines.push(`- blocks: ${list(pattern.blocks, 8)}`)
  }
  if (pattern.hooks !== undefined && pattern.hooks.length > 0) {
    lines.push(`- hooks: ${list(pattern.hooks, 6)}`)
  }
  if (pattern.valueKeys !== undefined && pattern.valueKeys.length > 0) {
    lines.push(`- value keys: ${pattern.valueKeys.join(" · ")}`)
  }
  if (pattern.exports.length > 0) lines.push(`- exports: ${list(pattern.exports, 6)}`)
  const relations = relationLine(pattern)
  if (relations !== "") lines.push(`- relations: ${relations}`)
  return lines
}

/** The human reading of the pattern view. */
export const renderPatterns = (view: PatternView): string => {
  const lines: Array<string> = [
    "# Patterns",
    "",
    `Generated by cutlist from \`${view.hash.slice(0, 12)}\`. The menu is the inventory; this is the shape.`,
    "",
    "A pattern has a context (tier, owners, feature), forces (adoption, variants, lifecycle), a solution (exports and composition), and relations to the patterns around it. Authored sentences come from `intent/`; everything else is derived.",
    "",
    `## stable shape (${view.stable.length})`,
    "",
    "The load-bearing parts and compositions, ranked by the facts below. A high score is a thing to build on; a low score is a thing to question, not automatically a thing to delete.",
    "",
  ]
  for (const pattern of view.stable) lines.push(...patternLine(pattern))
  lines.push("")

  lines.push(`## compositions (${view.compositions.length})`, "")
  for (const pattern of view.compositions) {
    lines.push(...compositionSection(pattern))
    lines.push("")
  }

  lines.push(`## primitives (${view.primitives.length})`, "")
  for (const pattern of view.primitives) lines.push(...patternLine(pattern))
  lines.push("")

  lines.push(`## load-bearing shared (${view.shared.length})`, "")
  for (const pattern of view.shared) lines.push(...patternLine(pattern))
  lines.push("")

  lines.push(`## variant families (${view.families.length})`, "")
  lines.push(
    "A family is a demand signal: the system is being worked around. The canonical is the member with the most importers.",
    "",
  )
  for (const pattern of view.families) {
    const variants = pattern.relations
      .filter((relation) => relation.kind === "variant-of")
      .map((relation) => relation.target)
    lines.push(`### \`${pattern.name}\` — keep \`${pattern.path}\``, "")
    lines.push(
      `- stability: ${pattern.stability.toFixed(2)} — ${factorLine(pattern)}`,
      `- canonical: \`${pattern.path}\`; ${plural(pattern.usedBy, ["importer", "importers"])}`,
      `- variants: ${variants.length === 0 ? "none" : list(variants, 8)}`,
    )
    const text = authoredLines(pattern)
    if (text.length > 0) lines.push(`- authored: ${text.join(" — ")}`)
    lines.push("")
  }
  if (view.families.length === 0) lines.push("- none", "")

  lines.push("## entropy signals", "")
  lines.push(
    "Signals for the tools that reign the codebase and for the next discovery pass. Cutlist does not compress: it shows where the vocabulary is under pressure, and leaves the move to Plumb, Joggle, or a person.",
    "",
  )
  lines.push(`### unreached (${view.signals.orphans.length})`, "")
  if (view.signals.orphans.length === 0) lines.push("- none")
  else {
    for (const orphan of view.signals.orphans.slice(0, 40)) lines.push(`- \`${orphan}\``)
    if (view.signals.orphans.length > 40) {
      lines.push(`- … ${String(view.signals.orphans.length - 40)} more in \`catalog.json\``)
    }
  }
  lines.push("")

  lines.push(`### variant families (${view.signals.variants.length})`, "")
  for (const variant of view.signals.variants.slice(0, 20)) {
    lines.push(
      `- canonical \`${variant.canonical}\`; variants ${list(variant.members, 6)} (the canonical is the most-used member, not a command)`,
    )
  }
  if (view.signals.variants.length === 0) lines.push("- none")
  if (view.signals.variants.length > 20) {
    lines.push(`- … ${String(view.signals.variants.length - 20)} more in \`patterns.json\``)
  }
  lines.push("")

  lines.push(`### retired in use (${view.signals.deprecated.length})`, "")
  if (view.signals.deprecated.length === 0) lines.push("- none")
  else for (const path of view.signals.deprecated) lines.push(`- \`${path}\``)
  lines.push("")

  return `${lines.join("\n").trimEnd()}\n`
}

/** The same view for an agent. */
export const renderPatternsJson = (view: PatternView): string =>
  `${JSON.stringify(view, null, 2)}\n`
