import {
  hasIntent,
  type Menu,
  type MenuEntry,
  type PartRole,
  type TierName,
} from "@autotelic/protocol"
import { authoredLines } from "./authored.ts"
import { plural } from "./text.ts"

/*
 * `menu.json` and `MENU.md`.
 *
 * The menu is the only mixed record in the artifact: half of an entry is derived (the
 * parts it is composed of) and half is authored (what it is for, what to reach for
 * instead). cutlist fills the derived half and joins the authored one; these renderers
 * never look past the menu, which is what keeps them from drifting from the model.
 *
 * `_(undocumented)_` reports the absence of any authored intent — the one flag here a
 * person can remove, and the reason the menu is not merely a rendering. `exports` and
 * `usedBy` are the two facts an agent needs before it can choose: what to import, and
 * whether anyone else already did.
 */

const TIER_ORDER: ReadonlyArray<TierName> = ["primitive", "shared", "local"]

/** The order a tier's kind groups appear in: entry points first, plumbing last. */
const MENU_KIND_ORDER: ReadonlyArray<PartRole> = [
  "route",
  "component",
  "provider",
  "hook",
  "context",
  "barrel",
  "module",
]

/**
 * A capped list, because the menu is an index and the catalog is the raw material.
 *
 * One `Dialog` exports eleven names and one provider can compose twenty atoms; printing
 * every one made the menu a quarter-megabyte of text a reader scrolls past. The first few
 * names answer "is this the thing I want"; the catalog and manifest carry the rest.
 */
const some = (items: ReadonlyArray<string>, limit: number): string => {
  const shown = items
    .slice(0, limit)
    .map((item) => `\`${item}\``)
    .join(", ")
  const rest = items.length - limit
  return rest > 0 ? `${shown} +${String(rest)} more` : shown
}

/** The menu model as JSON. The machine rendering an agent reads. */
export const renderMenuJson = (menu: Menu): string => `${JSON.stringify(menu, null, 2)}\n`

/**
 * One line of the index.
 *
 * The role tag names the part's SPECIFIC roles, not the default `component`: a route line
 * says `[route]`, a provider says `[provider]`, and ordinary components carry no tag. That is
 * the difference between an app index and a list of files.
 */
const entryLine = (entry: MenuEntry): string => {
  const extras = (entry.roles ?? []).filter((role) => role !== entry.kind && role !== "component")
  const shown =
    entry.kind === undefined || entry.kind === "component" || entry.kind === "module"
      ? extras
      : [entry.kind, ...extras]
  const kind = shown.length === 0 ? "" : ` \`[${shown.join(", ")}]\``
  const exportsOf =
    entry.exports === undefined || entry.exports.length === 0
      ? ""
      : ` — exports ${some(entry.exports, 3)}`
  const usage =
    entry.usedBy === undefined || entry.usedBy === 0 ? "" : ` — ${entry.usedBy} importers`
  const feature = entry.feature === undefined ? "" : ` — part of \`${entry.feature}\``
  const authored = authoredLines(entry)
  const summary = authored.length === 0 ? "" : ` — ${authored.join(" — ")}`
  const composed =
    entry.composedOf.length === 0 ? "" : ` — composed of ${some(entry.composedOf, 4)}`
  const flag = hasIntent(entry) ? "" : " _(undocumented)_"
  return `- \`${entry.name}\`${kind} — \`${entry.path}\`${exportsOf}${usage}${feature}${summary}${composed}${flag}`
}

/** The menu as Markdown — the same model, for a person or an agent's first look. */
export const renderMenu = (menu: Menu): string => {
  const lines: Array<string> = [
    "# UI menu",
    "",
    `Generated by cutlist; do not edit — run \`cutlist build\`. ${plural(menu.entries.length, ["part", "parts"])}.`,
    "",
  ]

  const health = menu.health
  if (health !== undefined) {
    lines.push("## health", "")
    lines.push(
      `- ${plural(health.parts, ["part", "parts"])}; ${health.documented} documented (${health.parts === 0 ? 0 : Math.round((health.documented / health.parts) * 100)}%)`,
      `- ${Math.round(health.sharedReach * 100)}% of local UI modules import a shared part; ${health.localOnly} local-only`,
      `- ${plural(menu.duplicates.length, ["candidate pair", "candidate pairs"])} in ${plural(health.duplicateClusters, ["cluster", "clusters"])}`,
      `- ${health.deprecatedInUse} deprecated ${health.deprecatedInUse === 1 ? "part" : "parts"} still imported`,
      "",
    )
  }

  const features = menu.features ?? []
  if (features.length > 0) {
    lines.push(`## features (${features.length})`, "")
    lines.push(
      "The composition pattern, where the tree attempts it: a context, a provider, one module per block, and a hook.",
      "",
    )
    for (const feature of features) {
      const blocks = plural(feature.blocks.length, ["block", "blocks"])
      const hooks = feature.hooks.length === 0 ? "" : `, ${some(feature.hooks, 3)}`
      const value = feature.valueKeys.length === 0 ? "" : ` — ${feature.valueKeys.join(" · ")}`
      lines.push(`- \`${feature.name}\` — \`${feature.dir}\` — ${blocks}${hooks}${value}`)
    }
    lines.push("")
  }

  for (const tier of TIER_ORDER) {
    const entries = menu.entries.filter((entry) => entry.tier === tier)
    lines.push(`## ${tier} (${entries.length})`, "")
    const groups = new Map<PartRole, Array<MenuEntry>>()
    for (const entry of entries) {
      const kind = entry.kind ?? "component"
      const group = groups.get(kind) ?? []
      group.push(entry)
      groups.set(kind, group)
    }
    if (groups.size <= 1) {
      for (const entry of entries) lines.push(entryLine(entry))
      lines.push("")
    } else {
      for (const kind of MENU_KIND_ORDER) {
        const group = groups.get(kind)
        if (group === undefined) continue
        lines.push(`### ${kind} (${group.length})`, "")
        for (const entry of group) lines.push(entryLine(entry))
        lines.push("")
      }
    }
  }

  const clusters = menu.clusters ?? []
  if (clusters.length > 0) {
    lines.push(`## duplicate clusters (${clusters.length})`, "")
    lines.push(
      "A cluster is a demand signal: the system is being worked around. The canonical is the member with the most importers, so a migration keeps the call sites that already exist.",
      "",
    )
    for (const cluster of clusters) {
      const others = cluster.members.filter((member) => member !== cluster.canonical)
      lines.push(
        `- \`${cluster.name}\` — ${plural(cluster.members.length, ["part", "parts"])}, ${plural(cluster.usedBy, ["importer", "importers"])}, max ${cluster.score.toFixed(2)} — keep \`${cluster.canonical}\`; also ${some(others, 4)}`,
      )
    }
    lines.push("")
  }

  if (menu.duplicates.length > 0) {
    const shown = menu.duplicates.slice(0, 12)
    lines.push(`## duplicate candidate pairs (${menu.duplicates.length})`, "")
    lines.push("Deterministic candidates; a judge decides whether two are one concept.", "")
    for (const duplicate of shown) {
      lines.push(`- \`${duplicate.left}\` ≈ \`${duplicate.right}\` (${duplicate.score.toFixed(2)})`)
    }
    if (shown.length < menu.duplicates.length) {
      lines.push(
        `- … ${String(menu.duplicates.length - shown.length)} more in \`menu.json\` and \`catalog.json\``,
      )
    }
    lines.push("")
  }

  if (menu.orphans.length > 0) {
    lines.push(`## orphans (${menu.orphans.length})`, "")
    for (const orphan of menu.orphans) lines.push(`- \`${orphan}\``)
    lines.push("")
  }

  return `${lines.join("\n").trimEnd()}\n`
}
