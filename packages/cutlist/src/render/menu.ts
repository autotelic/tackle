import type { Catalog, CatalogComponent, TierName } from "@autotelic/protocol"

/*
 * `MENU.md` — the model rendered for a human or an agent.
 *
 * Half of an entry is derived (composed of), half is authored (what it is for, what to
 * reach for instead). cutlist fills the derived half and scaffolds the entry; the
 * authored half is a person's, and its absence is what the `require-catalog-entry` rule
 * flags. Pretending a deterministic tool can write "do not use for" would be a lie
 * dressed as completeness.
 */

const TIER_ORDER: ReadonlyArray<TierName> = ["primitive", "shared", "local"]

/** What a component is made of, from its skeleton: rendered tags and called hooks. */
const composedOf = (component: CatalogComponent): ReadonlyArray<string> => {
  const parts = new Set<string>()
  for (const part of component.signature) {
    if (part.startsWith("tag:")) parts.add(part.slice(4))
    else if (part.startsWith("hook:")) parts.add(part.slice(5))
  }
  return [...parts]
}

/** The menu, as markdown. */
export const renderMenu = (catalog: Catalog): string => {
  const lines: Array<string> = [
    "# UI menu",
    "",
    `Generated by cutlist; do not edit — run \`cutlist build\`. ${catalog.components.length} components.`,
    "",
  ]

  for (const tier of TIER_ORDER) {
    const entries = catalog.components.filter((component) => component.tier === tier)
    lines.push(`## ${tier} (${entries.length})`, "")
    for (const component of entries) {
      const composed = composedOf(component)
      const suffix = composed.length === 0 ? "" : ` — composed of ${composed.join(", ")}`
      const flag = component.documented ? "" : " _(undocumented)_"
      lines.push(`- \`${component.name}\` — \`${component.path}\`${suffix}${flag}`)
    }
    lines.push("")
  }

  if (catalog.duplicates.length > 0) {
    lines.push(`## duplicate candidates (${catalog.duplicates.length})`, "")
    lines.push("Deterministic candidates; a judge decides whether two are one concept.", "")
    for (const duplicate of catalog.duplicates.slice(0, 40)) {
      lines.push(`- \`${duplicate.left}\` ≈ \`${duplicate.right}\` (${duplicate.score.toFixed(2)})`)
    }
    lines.push("")
  }

  if (catalog.orphans.length > 0) {
    lines.push(`## orphans (${catalog.orphans.length})`, "")
    for (const orphan of catalog.orphans) lines.push(`- \`${orphan}\``)
    lines.push("")
  }

  return `${lines.join("\n")}\n`
}
