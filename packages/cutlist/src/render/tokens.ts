import type { Catalog } from "@autotelic/protocol"

/** `tokens.md` — the four closed token sets, so the two layers are read side by side. */
export const renderTokens = (catalog: Catalog): string => {
  const lines: Array<string> = ["# Tokens", "", "Generated by cutlist.", ""]
  const sections: ReadonlyArray<readonly [string, ReadonlyArray<string>]> = [
    ["colors", catalog.tokens.colors],
    ["type", catalog.tokens.type],
    ["shape", catalog.tokens.shape],
    ["spacing", catalog.tokens.spacing],
  ]
  for (const [name, values] of sections) {
    lines.push(`## ${name} (${values.length})`, "")
    for (const value of values) lines.push(`- \`${value}\``)
    lines.push("")
  }
  return `${lines.join("\n")}\n`
}
