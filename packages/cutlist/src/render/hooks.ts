import { Order } from "effect"
import type { Catalog } from "@autotelic/protocol"

/** `hooks.md` — the hooks the app actually calls, discovered from the tree. */
export const renderHooks = (catalog: Catalog): string => {
  const hooks = new Set<string>()
  for (const component of catalog.components) {
    for (const part of component.signature) {
      if (part.startsWith("hook:")) hooks.add(part.slice(5))
    }
  }
  const lines: Array<string> = [
    "# Hooks",
    "",
    `Called across ${catalog.components.length} components. Generated by cutlist.`,
    "",
  ]
  for (const hook of [...hooks].sort(Order.String)) lines.push(`- \`${hook}\``)
  return `${lines.join("\n")}\n`
}
