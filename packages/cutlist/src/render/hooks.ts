import { Order } from "effect"
import type { Catalog } from "@autotelic/protocol"

/**
 * `hooks.md` — the hook vocabulary, in two directions.
 *
 * Declared hooks are parts: they have an identity, a path, and (eventually) intent, so an
 * agent can choose one rather than re-implement it. Called hooks are the vocabulary in
 * use — React's own plus the repo's — which is what a rule reads when it asks whether a
 * component reaches for an effect directly. The same parts list answers both; this is a
 * projection, not a second crawl.
 */
export const renderHooks = (catalog: Catalog): string => {
  const declared = catalog.components
    .filter((component) => component.roles?.includes("hook") === true)
    .flatMap((component) =>
      (component.declarations ?? [])
        .filter((declaration) => declaration.exported && declaration.name.startsWith("use"))
        .map((declaration) => ({ name: declaration.name, path: component.path })),
    )
    .sort((left, right) => left.name.localeCompare(right.name))

  const called = new Set<string>()
  for (const component of catalog.components) {
    for (const part of component.signature) {
      if (part.startsWith("hook:")) called.add(part.slice(5))
    }
  }

  const lines: Array<string> = ["# Hooks", "", "Generated by cutlist.", ""]
  if (declared.length > 0) {
    lines.push(`## declared (${declared.length})`, "")
    for (const hook of declared) lines.push(`- \`${hook.name}\` — \`${hook.path}\``)
    lines.push("")
  }
  lines.push(`## called (${called.size})`, "")
  for (const hook of [...called].sort(Order.String)) lines.push(`- \`${hook}\``)
  return `${lines.join("\n")}\n`
}
